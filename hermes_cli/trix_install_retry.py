"""Установка инструмента повторяется, а не сдаётся с первого раза.

Мастер ставил выбранные инструменты **одной попыткой**. Не получилось —
неудача записывалась в список, «Готово» всё равно объявляло успех, и
клиент оставался, например, без браузера, ничего для этого не сделав.

Большинство отказов здесь — сетевые: npm или pip не дотянулись до
зеркала, оборвалась загрузка, ответил не тот прокси. Такое лечится
повтором через несколько секунд. Отказы, которые повтором не лечатся
(нет нужного тулчейна на машине), повтор тоже не испортит — он просто
займёт немного времени и вернёт тот же честный отказ.

**Ограничение по времени обязательно.** Клиент ждёт ответа «Готово» в
браузере: одна установка живёт до 600 секунд, и три подряд без общего
потолка растянули бы отправку формы на полчаса. Поэтому у всего этапа
установки один бюджет на всех, и попытка не начинается, если на неё уже
не осталось времени.
"""

from __future__ import annotations

import logging
import time
from typing import Callable

logger = logging.getLogger(__name__)

# Пауза перед повтором. Короткая намеренно: это не фоновая задача, а
# нажатая кнопка — клиент смотрит на крутилку в браузере. Сетевая икота
# (сорвавшаяся загрузка, не отозвавшееся зеркало) проходит за секунды, а
# от того, что не проходит, не спасут и минуты ожидания.
RETRY_BACKOFF_SECONDS: tuple[float, ...] = (3.0, 9.0)

# Всего попыток на один инструмент: первая плюс по одной на каждую паузу.
# Значение по умолчанию; сама функция считает его на месте, читая
# RETRY_BACKOFF_SECONDS, — иначе подмена пауз в тесте (чтобы не ждать
# по-настоящему) разъезжалась бы с числом попыток и падала по индексу.
MAX_ATTEMPTS = len(RETRY_BACKOFF_SECONDS) + 1

# Общий потолок на ВЕСЬ этап установки, на все инструменты сразу.
INSTALL_STAGE_BUDGET_SECONDS = 900.0

# Меньше этого начинать новую попытку бессмысленно: она всё равно не
# успеет ничего скачать и только съест ожидание клиента.
MIN_SECONDS_FOR_ANOTHER_ATTEMPT = 45.0


def install_with_retries(
    key: str,
    runner: Callable[[str, float], dict],
    *,
    budget_left: float,
    sleep: Callable[[float], None] = time.sleep,
    monotonic: Callable[[], float] = time.monotonic,
) -> dict:
    """Ставить *key*, повторяя неудачу, пока есть время.

    *runner* получает ключ и потолок времени на ЭТУ попытку и возвращает
    словарь с ``ok``. Вызывающий отвечает за то, чтобы runner не бросал —
    здесь исключение не ловится намеренно: молча превратить поломку кода
    в «не установилось» значило бы спрятать её.

    Возвращает последний ответ runner-а плюс ``attempts`` (сколько
    попыток сделали) и ``spent`` (сколько секунд ушло) — обе величины
    нужны вызывающему, чтобы вести общий бюджет этапа.
    """
    started = monotonic()
    result: dict = {"ok": False}
    attempts = 0
    backoff = RETRY_BACKOFF_SECONDS
    max_attempts = len(backoff) + 1

    for index in range(max_attempts):
        spent = monotonic() - started
        remaining = budget_left - spent
        if attempts and remaining < MIN_SECONDS_FOR_ANOTHER_ATTEMPT:
            logger.info(
                "install %s: повтор не начат — на этап осталось %.0f с", key, remaining
            )
            break
        if remaining <= 0:
            break

        attempts += 1
        result = runner(key, remaining)
        if result.get("ok"):
            break

        if index < max_attempts - 1:
            pause = backoff[index]
            spent = monotonic() - started
            if budget_left - spent - pause < MIN_SECONDS_FOR_ANOTHER_ATTEMPT:
                logger.info("install %s: на повтор после паузы времени нет", key)
                break
            logger.info(
                "install %s: попытка %d не удалась, повтор через %.0f с",
                key, attempts, pause,
            )
            sleep(pause)

    out = dict(result)
    out["attempts"] = attempts
    out["spent"] = monotonic() - started
    return out


def retry_hint(attempts: int) -> str:
    """Что сказать клиенту, когда повторы всё равно не помогли.

    Нажать «Готово» ещё раз — рабочий путь, а не отговорка: этап
    установки берёт то, что выбрано И ещё не установлено, поэтому
    неудавшийся инструмент попадёт в него снова.
    """
    if attempts > 1:
        return (
            f"Пробовали {attempts} раза подряд. Нажмите «Готово» ещё раз — "
            "установка повторится; если не поможет и в третий раз, напишите "
            "в поддержку."
        )
    return "Нажмите «Готово» ещё раз — установка повторится."
