# Комментарий, который встаёт рядом с дописанным элементом списка — короткое
# объяснение в том же тоне, что и у соседних строк шаблона (см.
# ``assets/config/trix-config.yaml``, ``platform_toolsets.telegram``).
_TOOLSET_ENTRY_COMMENTS = {
    "mcp": "агент подключает MCP-серверы по вашей просьбе в чате",
}

# Строка-элемент YAML-списка на верхнем уровне блока ("- значение" или
# "- значение # комментарий"), без вложенных отображений/многострочных
# скаляров — этого достаточно для строкового списка тулсетов, других форм
# в ``platform_toolsets.<платформа>`` не бывает.
_LIST_ITEM_RE = re.compile(r"^(?P<indent>[ \t]*)-\s+(?P<val>[^\s#]+)")

# Строка, похожая на обычный YAML-ключ блочного отображения ("key:" или
# "key: value"). Используется, чтобы отличить настоящих потомков-ключей от
# flow-отображения/элемента списка/чего угодно ещё, продолжающего значение
# родителя на следующей строке той же вложенности.
_KEY_LINE_RE = re.compile(r"^[A-Za-z0-9_.\-]+:(\s|$)")

# Маркер конца документа YAML: "..." на нулевом отступе (допускается
# хвостовой комментарий). Всё, что дописано ПОСЛЕ него, — уже второй
# документ в потоке, и ``yaml.safe_load`` на таком файле падает с
# ``expected '<document start>'``. Клиентский файл, который им
# заканчивается, задаёт форму «документ здесь закончился», и корневые
# блоки обязаны вставляться ПЕРЕД маркером.
_DOC_END_RE = re.compile(r"^\.\.\.\s*(#.*)?$")


def _indent_of(line: str) -> int:
    return len(line) - len(line.lstrip(" "))


def _find_key_line(lines: list, key: str, indent: int, start: int, end: int) -> Optional[int]:
    """Найти строку ``key:`` на заданном отступе в ``lines[start:end]``."""
    pattern = re.compile(r"^" + " " * indent + re.escape(str(key)) + r":(\s|$)")
    for i in range(start, end):
        if pattern.match(lines[i]):
            return i
    return None


def _block_extent(lines: list, key_idx: int, indent: int) -> tuple:
    """Вернуть ``(start, end)`` блока, начинающегося строкой ``lines[key_idx]``.

    ``start`` включает непосредственно предшествующие строки-комментарии на
    том же отступе (без разрыва пустой строкой). ``end`` — индекс,
    исключающий, после последней строки с бо́льшим отступом (пустые строки
    внутри блока сохраняются, а пустая строка перед следующим блоком — нет).
    """
    start = key_idx
    i = key_idx - 1
    while i >= 0:
        line = lines[i]
        stripped = line.strip()
        if stripped and _COMMENT_RE.match(line) and _indent_of(line) == indent:
            start = i
            i -= 1
            continue
        break

    last_content = key_idx
    i = key_idx + 1
    n = len(lines)
    while i < n:
        line = lines[i]
        if line.strip() == "":
            i += 1
            continue
        if _indent_of(line) > indent:
            last_content = i
            i += 1
            continue
        break

    return start, last_content + 1


def _child_indent(lines: list, parent_idx: int, parent_end: int) -> Optional[int]:
    """Отступ прямых потомков блока, начинающегося в ``parent_idx``.

    Комментарии в расчёт НЕ берутся — тот же инвариант, что и для клиентского
    файла (:func:`_client_child_indent`): отступ комментария в YAML не значит
    ничего, парсер его не видит, поэтому решением о форме он быть не может.
    Раньше здесь считалась первая непустая строка, комментарии включительно, и
    один кураторский комментарий в шаблоне, отбитый иначе, чем его соседи,
    уводил отступ в сторону — а вместе с ним все глубокие ключи этого раздела
    молча уходили в пропуск.
    """
    for i in range(parent_idx + 1, parent_end):
        if _is_shape_bearing(lines[i]):
            return _indent_of(lines[i])
    return None


def _is_safe_block_parent_line(line: str, key: str, indent: int) -> bool:
    """True когда ``line`` — «голый» блочный ключ, под который можно
    безопасно вставить блочных потомков (строки с бо́льшим отступом).

    ``display: null``, ``display: ~``, ``display: {}`` и
    ``display: {cleanup_progress: true}`` — всё это валидные строки, где
    значение ключа уже полностью задано ПРАВЕЕ двоеточия на этой же
    строке. Дописать под такой строкой ещё и блочных потомков —
    невалидный YAML (``expected <block end>, but found ...``): парсер
    видит скаляр/flow-отображение, а затем внезапный более глубокий
    отступ, который к этому значению не относится. Безопасно вставлять
    можно только когда справа от двоеточия нет ничего, кроме пробелов и,
    может быть, комментария — то есть когда сама строка уже говорит
    «значение — ниже, в виде блока».
    """
    pattern = re.compile(r"^" + " " * indent + re.escape(str(key)) + r":\s*(#.*)?$")
    return bool(pattern.match(line))


def _is_shape_bearing(line: str) -> bool:
    """True для строки, которая ДЛЯ ПАРСЕРА что-то значит.

    Пустая строка и строка-комментарий формы не несут: YAML-парсер их не
    видит вовсе, отступ комментария не обязан совпадать ни с чем и ничего
    не задаёт. Это ровно то место, где неточная формулировка инварианта
    («решение выводится из клиентского файла») позволяла комментарию стать
    источником решения о форме — и ломала конфиг клиента.
    """
    return line.strip() != "" and not _COMMENT_RE.match(line)


def _client_block_has_shape(lines: list, parent_idx: int, parent_end: int) -> bool:
    """Есть ли у клиентского блока форма, которой вставка может противоречить.

    Форму задают только содержательные строки. Блок пустой или состоящий
    ТОЛЬКО из комментариев формы не имеет — противоречить нечему, значит
    заполнять его безопасно (на отступе шаблона).
    """
    return any(_is_shape_bearing(lines[i]) for i in range(parent_idx + 1, parent_end))


def _client_child_indent(
    lines: list, parent_idx: int, parent_end: int, parent_indent: int = 0
) -> Optional[int]:
    """Отступ прямых потомков — выведенный из СОДЕРЖАТЕЛЬНЫХ строк клиентского блока.

    Вызывается только когда :func:`_client_block_has_shape` истинна, то
    есть содержательная строка в блоке точно есть.

    Комментарии и пустые строки в расчёт НЕ берутся: отступ комментария в
    YAML не значит ничего, и минимальный отступ, посчитанный вместе с
    комментариями, уводил вставку на уровень, которого у детей нет —
    ``display:`` → `` # note`` → ``  tool_progress: "off"`` давал 1 вместо
    2, после чего ``yaml.safe_load`` падал на всём файле.

    Возвращает ``None``, когда форма есть, но вставке она противоречит:

    - минимальный отступ содержательных строк не больше отступа самого
      родителя (``parent_indent``): потомок обязан быть отбит правее, иначе
      он потомком не является. При спуске на любую глубину сравнивать
      нужно именно с родителем, а не с нулём — на третьем уровне родитель
      сам сидит на отступе 2, и «потомок» на отступе 2 это его сосед.
      Тот же ноль даёт строка с ТАБУЛЯЦИЕЙ: :func:`_indent_of` считает
      только ведущие пробелы, поэтому табулированная строка молча читается
      как 0 — отказ превращает это в честное «вывести нельзя» вместо
      ошибочного «отступ годится»;
    - хотя бы одна содержательная строка на минимальном отступе не похожа
      на обычный ``key:`` (например ``{cleanup_progress: true}`` —
      flow-отображение, продолжающее значение родителя на следующей
      строке, а не блочный потомок; или элемент списка ``- ...``).

    Более глубоко вложенные строки (списки, вложенные словари под одним из
    потомков) отступ не портят и не проверяются — они часть значения
    потомка, а не сами потомки.
    """
    min_indent = None
    for i in range(parent_idx + 1, parent_end):
        line = lines[i]
        if not _is_shape_bearing(line):
            continue
        indent = _indent_of(line)
        if min_indent is None or indent < min_indent:
            min_indent = indent
    if min_indent is None or min_indent <= parent_indent:
        return None

    for i in range(parent_idx + 1, parent_end):
        line = lines[i]
        if not _is_shape_bearing(line) or _indent_of(line) != min_indent:
            continue
        if not _KEY_LINE_RE.match(line.strip()):
            return None
    return min_indent


def _root_insert_index(lines: list) -> int:
    """Индекс, ПЕРЕД которым дописывается новый корневой блок.

    Обычно это физический конец файла. Но если клиентский документ
    закрыт маркером ``...``, то конец файла — уже за пределами документа:
    дописанная там секция стала бы вторым документом в потоке, и
    ``yaml.safe_load`` перестал бы читать файл целиком. Позиция вставки —
    такое же решение о форме, как отступ и разделитель строк, и выводится
    она из структуры клиентского документа, а не из привычки «дописываем в
    конец».

    Индекс не кэшируется вызывающим кодом, а пересчитывается перед каждой
    вставкой: врезка второго уровня могла сдвинуть маркер.
    """
    for i, line in enumerate(lines):
        if _DOC_END_RE.match(line):
            return i
    return len(lines)


def _reindent_block(block: list, from_indent: int, to_indent: int) -> list:
    """Переотбить строки блока, вырезанного из шаблона, под клиентский отступ.

    Сдвигает КАЖДУЮ непустую строку на одну и ту же дельту
    (``to_indent - from_indent``) — относительная вложенность внутри блока
    (списки, более глубоко вложенные ключи) сохраняется, потому что все
    строки блока изначально отступлены не меньше, чем ``from_indent``.
    Пустые строки не трогаются.
    """
    delta = to_indent - from_indent
    if delta == 0:
        return list(block)
    result = []
    for line in block:
        if line.strip() == "":
            result.append(line)
            continue
        new_indent = max(0, _indent_of(line) + delta)
        result.append(" " * new_indent + line.lstrip(" "))
    return result


def _path_exists(data, parts: list) -> bool:
    """Разрешается ли путь (список ключей) в разобранном отображении."""
    cur = data
    for part in parts:
        if not isinstance(cur, dict) or part not in cur:
            return False
        cur = cur[part]
    return True


def _preserves_client_values(old, new) -> bool:
    """Уцелело ли ДОСЛОВНО всё, что у клиента уже было.

    Это единственная проверка в модуле, которая смотрит не на текст, а на
    РЕЗУЛЬТАТ: то, что получилось после врезки, разбирается обратно и
    сравнивается с тем, что клиент имел до неё. Каждый ключ обязан
    сохраниться, и каждое значение — совпасть дословно. Новые ключи
    появляться можно (ради них всё и затевается), менять существующие —
    нельзя.

    Единственное послабление: клиентский ``None`` (голый ``key:`` без
    содержимого) законно превращается в словарь — это и есть заполнение
    пустого блока. ``None`` -> скаляр/список по-прежнему считается порчей.

    Сравнение типов строгое (``type(old) is type(new)``), иначе ``True``
    прошло бы за ``1``, а ``1`` — за ``1.0``.
    """
    if isinstance(old, dict):
        if not isinstance(new, dict):
            return False
        for key, oval in old.items():
            if key not in new:
                return False
            if not _preserves_client_values(oval, new[key]):
                return False
        return True
    if old is None:
        return new is None or isinstance(new, dict)
    if type(old) is not type(new):
        return False
    return bool(old == new)


def _preserves_client_values_growable(old, new, growable: set, path: tuple = ()) -> bool:
    """Как :func:`_preserves_client_values`, но спискам на путях из
    ``growable`` разрешено ДОПОЛНЯТЬСЯ новыми элементами в конец, не теряя
    и не переставляя ни одного старого.

    Нужна ровно :func:`sync_toolset_list_entries`: та единственная функция
    в модуле, которая намеренно меняет значение, которое у клиента уже
    было, — список тулсетов растёт. Для всего остального (включая другие
    списки на том же уровне вложенности, не упомянутые в ``growable``)
    поведение дословно то же, что у :func:`_preserves_client_values` —
    никакого послабления по умолчанию.
    """
    if path in growable:
        if not isinstance(old, list) or not isinstance(new, list):
            return False
        return new[: len(old)] == old
    if isinstance(old, dict):
        if not isinstance(new, dict):
            return False
        for key, oval in old.items():
            if key not in new:
                return False
            if not _preserves_client_values_growable(oval, new[key], growable, path + (key,)):
                return False
        return True
    if old is None:
        return new is None or isinstance(new, dict)
    if type(old) is not type(new):
        return False
    return bool(old == new)


def _toolset_entry_key(path: tuple, entry: str) -> str:
    """Ключ sidecar-отметки для одного дописанного элемента списка.

    Отдельная форма от путей :func:`sync_missing_client_sections` (те
    всегда ведут к словарному ключу — см. :func:`_collect_missing_paths`,
    "лист уже на месте" — путь до элемента внутри списка через неё
    НИКОГДА не возникает), поэтому коллизий в общем sidecar-файле
    (:func:`_load_seeded_paths`) быть не может: ``"platform_toolsets.
    telegram[mcp]"`` не совпадёт ни с одним путём вида ``"a.b.c"``.
    """
    return f"{_dotted(path)}[{entry}]"


#: Признак «результат не разобрался». Отдельно от ``None`` («врезка испортила
#: значение клиента»): причины разные, и саппорту нужно знать какая.
_UNPARSEABLE = object()


def _verify(new_text: str, client_data: dict, added: list):
    """Проверить РЕЗУЛЬТАТ врезки перед тем, как что-либо записать.

    Возвращает список путей, которые текстово врезаны, но до разобранного
    конфига не доехали (пустой список — всё в порядке); :data:`_UNPARSEABLE`,
    если получившийся текст не разбирается; ``None``, если разбирается, но
    врезка изменила что-то из того, что у клиента уже было. Две последние
    беды разведены намеренно: причина уходит оператору, и «не парсится»
    отправляет его в другое место, чем «испортило значение».

    **Зачем эта проверка существует.** Всё остальное в модуле — построчный
    сканер, и он может разойтись с парсером в том, КАКАЯ строка владеет
    ключом. Многострочный кавычечный скаляр, продолжение которого стоит на
    колонке 0, текстом неотличим от корневого ключа::

        agent:
          system_prompt_extra: "Ты Trix.
        web:
        Всегда отвечай по-русски."
        web:
          search_backend: ddgs

    ``web:`` на второй строке принадлежит СТРОКЕ, а сканер видит корневой
    ключ и врезает в него. С двойными кавычками файл после этого не
    парсится; с одинарными — парсится, но значение клиента молча
    переписано, и ни «ни одна строка не изменилась», ни свёртка по формам
    этого не видят: строки-то все на месте.

    Ловить такое шестым текстовым спецкейсом бессмысленно — форм всегда
    найдётся ещё одна. Ловится это только разбором того, что получилось, и
    сверкой с тем, что было. Эта же проверка поймала бы все четыре
    предыдущих круга (разделитель, инлайн-родитель, отступ, маркер
    документа), не расширяя ни одной регулярки.
    """
    try:
        new_data = yaml.safe_load(new_text)
    except Exception:
        return _UNPARSEABLE
    if not isinstance(new_data, dict):
        return _UNPARSEABLE
    if not _preserves_client_values(client_data, new_data):
        return None
    return [path for path in added if not _path_exists(new_data, list(path))]


def _dotted(path: tuple) -> str:
    """Человекочитаемая запись пути — только для отчёта и sidecar-отметки.

    Внутри модуля путь всегда КОРТЕЖ ключей. Точка разделителем быть не
    может: в ``DEFAULT_CONFIG`` есть ключи с точкой внутри имени
    (``monitoring.gateway_health_export.resource_attributes`` содержит
    ``service.name`` и ``deployment.environment.name``), и ``split(".")``
    искал бы у них ключ ``service``, которого нет. Обратно из строки путь
    не разбирается нигде — она только показывается человеку и кладётся в
    sidecar.
    """
    return ".".join(str(part) for part in path)


def _descendant_paths(subtree, prefix: tuple) -> list:
    """Все пути внутри ``subtree``, включая промежуточные словари.

    Нужен для sidecar-отметки: дописав блок целиком, мы обязаны отметить
    доставленным не только его корень, но и каждый ключ внутри — иначе
    следующий прогон увидит родителя на месте и попробует довставить в него
    подключ, который клиент только что сознательно удалил.
    """
    if not isinstance(subtree, dict):
        return []
    out = []
    for key, value in subtree.items():
        child = prefix + (key,)
        out.append(child)
        out.extend(_descendant_paths(value, child))
    return out


def _collect_missing_paths(tdata: dict, cdata, prefix: tuple = ()) -> list:
    """Пути (кортежи ключей), присутствующие в ``tdata``, но не в ``cdata``.

    Ключевое свойство: рекурсия спускается в подсловарь только когда ключ
    ЕСТЬ у клиента и является словарём и там, и там — а значит для любого
    возвращённого пути глубины >= 2 гарантированно, что все его предки уже
    существуют у клиента как словари. Отсутствующий целиком родитель
    возвращается ОДНИМ путём (без рекурсии внутрь) — его блок вставляется
    целиком, как единое целое.

    Клиентский ``None`` на месте словаря (``display:`` без содержимого)
    трактуется как пустой словарь — иначе пустая секция блокировала бы
    досев всего, что должно быть под ней.
    """
    missing = []
    if not isinstance(cdata, dict):
        cdata = {}
    for key, tval in tdata.items():
        path = prefix + (key,)
        if key not in cdata:
            missing.append(path)
            continue
        if isinstance(tval, dict):
            cval = cdata.get(key)
            if cval is None:
                cval = {}
            if not isinstance(cval, dict):
                # Клиент переопределил структуру (у него скаляр/список там,
                # где шаблон ожидает словарь) — прививать в это нечего и
                # опасно, оставляем как есть целиком.
                continue
            missing.extend(_collect_missing_paths(tval, cval, path))
        # tval не словарь и ключ у клиента есть — лист уже на месте.
    return missing


def _dominant_newline(text: str) -> str:
    """Разделитель строк, преобладающий в тексте — ``"\\r\\n"`` или ``"\\n"``."""
    crlf = text.count("\r\n")
    lf_only = text.count("\n") - crlf
    return "\r\n" if crlf > lf_only else "\n"


def _read_raw_text(path: Path) -> str:
    """Прочитать файл, сохранив исходные символы конца строки буквально.

    ``Path.read_text()`` в универсальном текстовом режиме превращает
    ``\\r\\n`` в ``\\n`` на чтении — после этого различить, каким
    разделителем пользовался клиентский файл, уже нельзя. ``newline=""``
    отключает это преобразование.
    """
    with open(path, "r", encoding="utf-8", newline="") as f:
        return f.read()


def _seeded_state_path() -> Path:
    from hermes_constants import get_hermes_home

    return get_hermes_home() / SEEDED_STATE_FILENAME


def _load_seeded_paths() -> dict:
    """Пути, уже дописанные досевом ранее — их отсутствие больше не чинится.

    Отсутствующий, битый, нечитаемый или НЕ-UTF-8 файл — не ошибка: значит,
    ничего ещё не отмечено, досев продолжает работать как обычно (просто
    без защиты от воскрешения удалённого клиентом ключа на этот конкретный
    прогон). ``except Exception`` намеренно широкий — контракт этой функции
    «любая проблема с sidecar-файлом -> {}», и она вызывается ДО общего
    ``try`` в :func:`sync_missing_client_sections`, так что любое
    исключение отсюда иначе улетело бы наружу и уронило бы весь досев
    целиком, а не только защиту от воскрешения.
    """
    path = _seeded_state_path()
    try:
        raw = path.read_text(encoding="utf-8")
    except Exception:
        return {}
    try:
        data = json.loads(raw)
    except Exception:
        return {}
    return data if isinstance(data, dict) else {}


def _save_seeded_paths(data: dict) -> None:
    """Best-effort — неудача не должна отменять уже сделанный досев."""
    try:
        path = _seeded_state_path()
        path.parent.mkdir(parents=True, exist_ok=True)
        atomic_write_text(
            path,
            json.dumps(data, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        )
    except Exception:
        pass


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def added_summary(added: list, *, max_sections: int = 8) -> str:
    """Короткая строка про досеянное — для показа человеку.

    Пока шаблон был дельтой, вызывающие печатали ``", ".join(added)``: путей
    было единицы. С полным шаблоном первый досев на работающей машине даёт
    **238** путей, то есть одну строку в 5243 символа. Она уезжает не только
    в консоль: ``update`` есть в клиентском меню Телеграма, а у Телеграма
    предел сообщения 4096 символов — то есть отчёт об успешном обновлении
    ронял бы отправку.

    Поэтому наружу идёт счёт и НАЗВАНИЯ РАЗДЕЛОВ (корневые ключи), а полный
    список путей остаётся в логе: раздел — это то, что человек может пойти и
    посмотреть в файле, а 238 путей ему всё равно не прочитать.
    """
    if not added:
        return ""
    roots = []
    for path in added:
        root = str(path).split(".", 1)[0]
        if root not in roots:
            roots.append(root)
    shown = ", ".join(roots[:max_sections])
    if len(roots) > max_sections:
        shown += f" и ещё {len(roots) - max_sections}"
    return f"{len(added)} настроек в разделах: {shown}"


def sync_missing_client_sections(config_path: Path, template_path: Path) -> tuple:
    """Дописать в ``config_path`` то, чего нет, но есть в ``template_path``.

    Сравнение — по наличию ключа, не по значению: значение клиента всегда
    побеждает, дописывается только отсутствующее. Путь, однажды дописанный
    (см. модульный докстринг про sidecar-отметку), при последующем удалении
    клиентом больше не восстанавливается.

    Возвращает ``(added, skipped)``: ``added`` — список дописанных путей;
    ``skipped`` — список пар ``(путь, причина)`` для путей, которые НЕ
    вставлялись (глубже двух уровней; родитель с инлайн-значением; отступ
    детей нельзя надёжно вывести из клиентского файла — см. модульный
    докстринг и ``_SKIP_*`` константы). Оба пустых списка означает «всё на
    месте» (в том числе при любой ошибке — нечитаемый/неразбираемый шаблон,
    нечитаемый или защищённый от записи клиентский файл — файл в этом
    случае остаётся нетронутым).
    """
    config_path = Path(config_path)
    template_path = Path(template_path)

    try:
        client_text = _read_raw_text(config_path)
    except Exception:
        # НЕ ``except OSError``: не-UTF-8 клиентский файл бросает
        # ``UnicodeDecodeError`` — потомка ``ValueError``, а не ``OSError``, —
        # и этот вызов стоит ДО общего ``try`` ниже, так что исключение
        # улетело бы наружу. Контракт модуля «любая ошибка -> пустой
        # результат, файл не тронут» должен выполняться буквально для любой
        # ошибки. Ровно этот же пробел уже чинился в ``_load_seeded_paths``
        # (круг 2) — здесь он оставался.
        return [], []

    # Уважать защиту, которую клиент поставил руками: read-only файл не
    # переписывается, даже если каталог, где он лежит, доступен на запись
    # (атомарная замена создаёт временный файл в каталоге — ей достаточно
    # прав на каталог, а не на сам файл).
    if not os.access(config_path, os.W_OK):
        return [], []

    try:
        template_text = _read_raw_text(template_path)
    except Exception:
        return [], []

    try:
        client_data = yaml.safe_load(client_text)
    except yaml.YAMLError:
        return [], []
    try:
        template_data = yaml.safe_load(template_text)
    except yaml.YAMLError:
        return [], []

    if client_data is None:
        client_data = {}
    if not isinstance(client_data, dict) or not isinstance(template_data, dict):
        return [], []

    try:
        missing_paths = _collect_missing_paths(template_data, client_data)
    except Exception:
        return [], []

    if not missing_paths:
        return [], []

    template_lines = template_text.splitlines()
    client_sep = _dominant_newline(client_text)
    had_trailing_newline = client_text.endswith(("\n", "\r"))
    client_lines = client_text.splitlines()

    try:
        # Inside the try, not before it: _load_seeded_paths() is hardened
        # to never raise, but keeping the call inside this guard is a
        # second line of defense against exactly the "helper call sits
        # outside the general try" class of bug.
        seeded = _load_seeded_paths()

        def _splice(exclude: set) -> tuple:
            """Один проход врезки. Чистая функция от ``client_lines``: сам
            список не мутируется, возвращается новый.

            ``exclude`` — пути, которые этот проход не трогает вовсе.
            Используется вторым проходом, когда проверка результата
            показала, что какая-то врезка не дошла до парсера.
            """
            lines = list(client_lines)
            added = []
            skipped = []

            for path in missing_paths:
                if path in exclude:
                    continue

                if _dotted(path) in seeded:
                    # Клиент сознательно стёр то, что мы уже дописывали —
                    # уважаем это, не воскрешаем. Причина попадает в
                    # ``skipped``, а не теряется молча: без неё саппорт не
                    # может объяснить, почему настройка не возвращается.
                    skipped.append((_dotted(path), _SKIP_DELETED_BY_CLIENT))
                    continue

                if len(path) == 1:
                    key = path[0]
                    root_idx = _find_key_line(template_lines, key, 0, 0, len(template_lines))
                    if root_idx is None:
                        skipped.append((_dotted(path), _SKIP_NOT_IN_TEMPLATE))
                        continue
                    b_start, b_end = _block_extent(template_lines, root_idx, 0)
                    block = template_lines[b_start:b_end]
                    # Не «в конец файла», а «в конец ДОКУМЕНТА»: маркер `...`
                    # закрывает документ, и всё после него — второй документ.
                    insert_at = _root_insert_index(lines)
                    to_insert = list(block)
                    if insert_at > 0 and lines[insert_at - 1].strip() != "":
                        to_insert.insert(0, "")
                    lines[insert_at:insert_at] = to_insert
                    added.append(path)
                    continue

                # Любой уровень глубже первого. _collect_missing_paths
                # гарантирует, что каждый ПРЕДОК пути уже существует у
                # клиента как словарь (или как None, что мы трактуем как
                # пустой словарь) — но ТЕКСТОВО предок может быть чем
                # угодно: голым блочным ключом, скаляром/null/~ на той же
                # строке, flow-отображением ``{}``/``{...}``, или с детьми,
                # отбитыми другим отступом, чем в шаблоне. Каждая из этих
                # форм — своя причина для skipped, а форматирование вставки
                # (сам отступ) выводится ТОЛЬКО из клиентского блока,
                # никогда из шаблона.
                #
                # Спуск идёт по ОБОИМ файлам независимо: по клиентскому —
                # чтобы найти, куда вставлять и на каком отступе; по
                # шаблону — чтобы найти, что именно вставлять. Раньше это
                # была развёрнутая вручную единственная итерация (parts ==
                # [key, subkey]) с явным отказом от всего, что глубже;
                # проверки формы в теле цикла те же самые, слово в слово.
                ancestors, leaf = path[:-1], path[-1]

                # --- спуск по клиентскому файлу -----------------------
                c_start, c_end, c_indent = 0, len(lines), 0
                parent_end_c = None
                parent_own_indent = 0
                client_child_indent = None
                failure = None
                last_ancestor = len(ancestors) - 1
                for depth, ancestor in enumerate(ancestors):
                    a_idx = _find_key_line(lines, ancestor, c_indent, c_start, c_end)
                    if a_idx is None:
                        # Разобранный конфиг говорит, что предок есть, а
                        # построчный сканер его не нашёл: ``terminal :`` с
                        # пробелом перед двоеточием, ``"terminal":`` в
                        # кавычках, BOM в начале файла. Раньше это был
                        # молчаливый ``continue`` — оператор видел
                        # «конфигурация актуальна» при недоехавших
                        # настройках и без единой строчки диагностики.
                        failure = _SKIP_PARENT_NOT_FOUND
                        break
                    if not _is_safe_block_parent_line(lines[a_idx], ancestor, c_indent):
                        failure = _SKIP_INLINE_PARENT
                        break
                    _, a_end = _block_extent(lines, a_idx, c_indent)
                    if _client_block_has_shape(lines, a_idx, a_end):
                        # У блока есть настоящие дети — их отступ и есть
                        # форма, которой вставка не имеет права
                        # противоречить.
                        child_indent = _client_child_indent(lines, a_idx, a_end, c_indent)
                        if child_indent is None:
                            failure = _SKIP_AMBIGUOUS_INDENT
                            break
                    else:
                        # Блок пуст или в нём только комментарии — формы,
                        # которой можно противоречить, нет. Отступ
                        # комментария парсер не видит, поэтому решением он
                        # быть не может; берём отступ шаблона (ниже,
                        # `client_child_indent is None` -> переотбивка с
                        # нулевой дельтой).
                        child_indent = None
                    parent_end_c = a_end
                    parent_own_indent = c_indent
                    client_child_indent = child_indent
                    if child_indent is None:
                        # Спускаться дальше некуда: у пустого блока детей
                        # нет. Для последнего предка это законно — мы его и
                        # заполняем. Глубже — состояние невозможное (пустой
                        # предок разбирается в {}, и тогда отсутствующим
                        # оказался бы он сам, путём короче), поэтому
                        # оборонительный отказ вместо угадывания.
                        if depth != last_ancestor:
                            failure = _SKIP_PARENT_NOT_FOUND
                        break
                    c_start, c_end, c_indent = a_idx + 1, a_end, child_indent
                if failure is not None:
                    skipped.append((_dotted(path), failure))
                    continue
                if parent_end_c is None:
                    skipped.append((_dotted(path), _SKIP_PARENT_NOT_FOUND))
                    continue

                # --- спуск по шаблону ---------------------------------
                t_start, t_end, t_indent = 0, len(template_lines), 0
                for ancestor in ancestors:
                    a_idx = _find_key_line(template_lines, ancestor, t_indent, t_start, t_end)
                    if a_idx is None:
                        failure = _SKIP_NOT_IN_TEMPLATE
                        break
                    _, a_end = _block_extent(template_lines, a_idx, t_indent)
                    a_child_indent = _child_indent(template_lines, a_idx, a_end)
                    if a_child_indent is None:
                        failure = _SKIP_NOT_IN_TEMPLATE
                        break
                    t_start, t_end, t_indent = a_idx + 1, a_end, a_child_indent
                if failure is not None:
                    skipped.append((_dotted(path), failure))
                    continue

                leaf_idx = _find_key_line(template_lines, leaf, t_indent, t_start, t_end)
                if leaf_idx is None:
                    skipped.append((_dotted(path), _SKIP_NOT_IN_TEMPLATE))
                    continue
                leaf_start, leaf_end = _block_extent(template_lines, leaf_idx, t_indent)
                block = template_lines[leaf_start:leaf_end]
                if client_child_indent is not None:
                    target_indent = client_child_indent
                else:
                    # Блок клиента пуст — своей формы у него нет, берём отступ
                    # шаблона. Но отступ шаблона НЕ ОБЯЗАН быть правее
                    # клиентского родителя: на двух уровнях родитель стоял на
                    # нуле и любой отступ шаблона годился, а на глубине 3+
                    # родитель сам отбит, и у клиента с широким отступом
                    # (`platforms` на 4, `telegram` на 8) шаблонные 6 дали бы
                    # строку ЛЕВЕЕ родителя. Это уже не потомок: файл
                    # перестаёт разбираться, проверка результата отклоняет
                    # проход целиком, и один такой путь уносит все остальные.
                    target_indent = max(t_indent, parent_own_indent + 2)
                block = _reindent_block(block, t_indent, target_indent)

                lines[parent_end_c:parent_end_c] = block
                added.append(path)
            return lines, added, skipped

        def _render(lines: list) -> str:
            return client_sep.join(lines) + (client_sep if had_trailing_newline else "")

        # --- проход 1 --------------------------------------------------
        lines, added, skipped = _splice(set())
        if not added:
            return [], skipped

        # --- проверка РЕЗУЛЬТАТА, а не текста ---------------------------
        # Всё, что выше, — построчный сканер, и он в принципе может
        # разойтись с парсером в том, КАКАЯ строка владеет ключом:
        # продолжение многострочного кавычечного скаляра, стоящее на
        # колонке 0, текстом неотличимо от корневого ключа. Ни один
        # текстовый спецкейс этого класса не закрывает — закрывает только
        # разбор того, что получилось, и сверка с тем, что было.
        new_text = _render(lines)
        verified = _verify(new_text, client_data, added)
        if verified is _UNPARSEABLE:
            return [], skipped + [(_dotted(p), _SKIP_VERIFY_UNPARSEABLE) for p in added]
        if verified is None:
            return [], skipped + [(_dotted(p), _SKIP_VERIFY_FAILED) for p in added]

        # --- проход 2, если какая-то врезка не дошла до парсера ---------
        ineffective = verified  # список: остальные случаи обработаны выше
        if ineffective:
            lines, added, skipped = _splice(set(ineffective))
            skipped += [(_dotted(p), _SKIP_NO_EFFECT) for p in ineffective]
            if not added:
                return [], skipped
            new_text = _render(lines)
            verified = _verify(new_text, client_data, added)
            if verified is _UNPARSEABLE:
                return [], skipped + [
                    (_dotted(p), _SKIP_VERIFY_UNPARSEABLE) for p in added
                ]
            if verified is None or verified:
                # Второй проход тоже не сходится — больше не гадаем.
                return [], skipped + [(_dotted(p), _SKIP_VERIFY_FAILED) for p in added]

        atomic_write_text(config_path, new_text, newline="", preserve_mode=True)

        # Отмечаем только то, что ДЕЙСТВИТЕЛЬНО доехало до разобранного
        # конфига: путь, чья врезка легла в текстовый блок, которым парсер
        # не владеет, доставленным не считается и остаётся кандидатом на
        # следующий прогон.
        stamp = _now_iso()
        newly_seeded = {_dotted(path): stamp for path in added}
        for path in added:
            # Вся вложенность внутрь только что дописанного блока тоже
            # отмечается — иначе следующий прогон увидит существующего
            # родителя и попробует довставить его подключ по отдельности,
            # не зная, что тот уже приезжал вместе с целым блоком и мог
            # быть сознательно удалён клиентом. Раньше отмечался ровно один
            # уровень внутрь, и только для корневых блоков: с врезкой на
            # любую глубину этого мало.
            subtree = template_data
            for part in path:
                if not isinstance(subtree, dict) or part not in subtree:
                    subtree = None
                    break
                subtree = subtree[part]
            for descendant in _descendant_paths(subtree, path):
                newly_seeded.setdefault(_dotted(descendant), stamp)

        if newly_seeded:
            seeded.update(newly_seeded)
            _save_seeded_paths(seeded)

        return [_dotted(path) for path in added], skipped
    except Exception:
        # Досев вызывается из `hermes update` и `doctor --fix` — падение
        # здесь не имеет права ронять их. Файл ещё не тронут: единственная
        # запись (atomic_write_text) идёт только после того, как весь цикл
        # выше отработал без исключений.
        return [], []


def _find_list_item_lines(lines: list, start: int, end: int) -> list:
    """Индексы строк-элементов списка (``- значение``) внутри ``lines[start:end]``.

    Отступ ПЕРВОГО найденного элемента становится отступом всего списка —
    у однородного списка (как ``platform_toolsets.telegram``) все элементы
    отбиты одинаково, а строка на другом отступе внутри того же диапазона
    (что при валидном YAML-списке недостижимо) в расчёт не берётся, а не
    рвёт список надвое.
    """
    found = []
    item_indent = None
    for i in range(start, end):
        m = _LIST_ITEM_RE.match(lines[i])
        if not m:
            continue
        indent = len(m.group("indent"))
        if item_indent is None:
            item_indent = indent
        elif indent != item_indent:
            continue
        found.append(i)
    return found


def sync_toolset_list_entries(config_path: Path) -> tuple:
    """Дописать тулсеты из :data:`_TOOLSET_ENTRY_MIGRATIONS` в уже
    существующий список ``platform_toolsets.<платформа>``, если их там ещё
    нет.

    Отдельная функция от :func:`sync_missing_client_sections`, а не
    расширение той — см. модульный докстринг, раздел «Второй, отдельный
    вид досева». Родителя (сам список) эта функция НИКОГДА не создаёт: он
    либо уже есть у клиента как список, либо путь пропускается целиком —
    доставкой отсутствующего родителя целиком заведует
    :func:`sync_missing_client_sections`, и он же довезёт вместе с ним всё
    содержимое, включая тулсеты из ``_TOOLSET_ENTRY_MIGRATIONS``, без
    участия этой функции.

    Возвращает ``(added, skipped)`` в том же формате, что и
    :func:`sync_missing_client_sections`: ``added`` — список меток вида
    ``"platform_toolsets.telegram[mcp]"``; ``skipped`` — пары
    ``(метка, причина)``. Идемпотентна: тулсет, уже присутствующий в
    списке клиента, повторно не дописывается, а второй прогон без
    изменений в файле возвращает ``([], [])``. Тулсет, который клиент
    сознательно удалил после того, как его когда-то дописал этот же
    механизм, не воскрешается — используется тот же sidecar-файл, что и
    :func:`sync_missing_client_sections` (:func:`_load_seeded_paths`).
    """
    config_path = Path(config_path)

    try:
        client_text = _read_raw_text(config_path)
    except Exception:
        return [], []

    if not os.access(config_path, os.W_OK):
        return [], []

    try:
        client_data = yaml.safe_load(client_text)
    except yaml.YAMLError:
        return [], []
    if not isinstance(client_data, dict):
        return [], []

    client_sep = _dominant_newline(client_text)
    had_trailing_newline = client_text.endswith(("\n", "\r"))
    lines = client_text.splitlines()

    try:
        seeded = _load_seeded_paths()
        added = []
        skipped = []

        for path, entries in _TOOLSET_ENTRY_MIGRATIONS.items():
            # Родителя (сам список) не создаём — если пути нет вовсе,
            # довезёт sync_missing_client_sections вместе со всем блоком.
            subtree = client_data
            missing_parent = False
            for key in path:
                if not isinstance(subtree, dict) or key not in subtree:
                    missing_parent = True
                    break
                subtree = subtree[key]
            if missing_parent:
                continue
            if not isinstance(subtree, list):
                # Клиент превратил список во что-то другое (null, "{}",
                # скаляр) — вставлять элементы некуда, форме противоречить
                # нельзя.
                continue

            wanted = []
            for entry in entries:
                if entry in subtree:
                    continue
                key = _toolset_entry_key(path, entry)
                if key in seeded:
                    # Клиент уже видел этот тулсет и сознательно его
                    # убрал — не воскрешаем, ровно как sidecar делает для
                    # sync_missing_client_sections.
                    skipped.append((key, _SKIP_DELETED_BY_CLIENT))
                    continue
                wanted.append(entry)
            if not wanted:
                continue

            # --- найти в тексте блок списка ---------------------------
            ancestors, leaf = path[:-1], path[-1]
            cur_start, cur_end, cur_indent = 0, len(lines), 0
            found_parent = True
            for key in ancestors:
                a_idx = _find_key_line(lines, key, cur_indent, cur_start, cur_end)
                if a_idx is None or not _is_safe_block_parent_line(lines[a_idx], key, cur_indent):
                    found_parent = False
                    break
                a_start, a_end = _block_extent(lines, a_idx, cur_indent)
                child_indent = _child_indent(lines, a_idx, a_end)
                if child_indent is None:
                    found_parent = False
                    break
                cur_start, cur_end, cur_indent = a_idx + 1, a_end, child_indent
            if not found_parent:
                for entry in wanted:
                    skipped.append((_toolset_entry_key(path, entry), _SKIP_PARENT_NOT_FOUND))
                continue

            leaf_idx = _find_key_line(lines, leaf, cur_indent, cur_start, cur_end)
            if leaf_idx is None or not _is_safe_block_parent_line(lines[leaf_idx], leaf, cur_indent):
                for entry in wanted:
                    skipped.append((_toolset_entry_key(path, entry), _SKIP_PARENT_NOT_FOUND))
                continue
            _, leaf_end = _block_extent(lines, leaf_idx, cur_indent)

            item_lines = _find_list_item_lines(lines, leaf_idx + 1, leaf_end)
            if not item_lines:
                # Разобранный список непуст (иначе wanted было бы уже
                # исчерпано выше), но построчный сканер ни одного элемента
                # не нашёл — форма клиентского списка не распознана
                # (комментарии-only, необычная вложенность).
                for entry in wanted:
                    skipped.append((_toolset_entry_key(path, entry), _SKIP_AMBIGUOUS_INDENT))
                continue

            last_item_idx = item_lines[-1]
            item_indent = len(_LIST_ITEM_RE.match(lines[last_item_idx]).group("indent"))

            new_lines = []
            for entry in wanted:
                label = f"- {entry}"
                comment = _TOOLSET_ENTRY_COMMENTS.get(entry)
                line = " " * item_indent + label
                if comment:
                    pad = max(2, 20 - len(label))
                    line += " " * pad + f"# {comment}"
                new_lines.append(line)

            insert_at = last_item_idx + 1
            lines[insert_at:insert_at] = new_lines
            for entry in wanted:
                added.append(_toolset_entry_key(path, entry))

        if not added:
            return [], skipped

        new_text = client_sep.join(lines) + (client_sep if had_trailing_newline else "")

        try:
            new_data = yaml.safe_load(new_text)
        except yaml.YAMLError:
            return [], skipped + [(a, _SKIP_VERIFY_UNPARSEABLE) for a in added]
        if not isinstance(new_data, dict):
            return [], skipped + [(a, _SKIP_VERIFY_UNPARSEABLE) for a in added]

        growable = set(_TOOLSET_ENTRY_MIGRATIONS.keys())
        if not _preserves_client_values_growable(client_data, new_data, growable):
            return [], skipped + [(a, _SKIP_VERIFY_FAILED) for a in added]

        # Каждый дописанный тулсет обязан реально оказаться в разобранном
        # списке на своём пути — иначе врезка легла не в тот текстовый
        # блок, которым владеет парсер (см. _SKIP_NO_EFFECT в модульном
        # докстринге sync_missing_client_sections).
        for path, entries in _TOOLSET_ENTRY_MIGRATIONS.items():
            subtree = new_data
            ok_path = True
            for key in path:
                if not isinstance(subtree, dict) or key not in subtree:
                    ok_path = False
                    break
                subtree = subtree[key]
            for entry in entries:
                key = _toolset_entry_key(path, entry)
                if key not in added:
                    continue
                if not (ok_path and isinstance(subtree, list) and entry in subtree):
                    return [], skipped + [(a, _SKIP_NO_EFFECT) for a in added]

        atomic_write_text(config_path, new_text, newline="", preserve_mode=True)

        stamp = _now_iso()
        seeded.update({key: stamp for key in added})
        _save_seeded_paths(seeded)

        return added, skipped
    except Exception:
        # Тот же контракт, что у sync_missing_client_sections: падение
        # здесь не имеет права ронять `hermes update`/`doctor --fix`.
        return [], []
