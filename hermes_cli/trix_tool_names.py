def russian_tool_action(tool_name: str | None) -> str | None:
    """Русская формулировка дела для инструмента, либо ``None``.

    ``None`` означает "не знаю" — вызывающий обязан показать строку без
    хвоста, а не подставлять английское имя.

    Принимает также «пачку» имён через запятую с пробелом — при
    параллельном вызове нескольких инструментов
    ``agent._current_tool`` (``agent/tool_executor.py:876,964``)
    становится строкой вида ``"read_file, web_search"``, а не одним
    именем. Прямой lookup такую строку целиком не находит (её и не
    может быть в словаре — она не имя инструмента), поэтому при
    промахе разбираем по ``", "`` и называем дело по первому известному
    куску: клиенту достаточно узнать, что агент читает файл, даже если
    заодно ищет в интернете. Модель батчит вызовы инструментов часто —
    без этого разбора заметная доля ходов молча теряла бы формулировку
    и откатывалась на голую строку без хвоста.
    """
    name = (tool_name or "").strip()
    if not name:
        return None
    direct = _ACTIONS.get(name)
    if direct:
        return direct
    if ", " in name:
        for part in name.split(", "):
            action = _ACTIONS.get(part.strip())
            if action:
                return action
    return None
