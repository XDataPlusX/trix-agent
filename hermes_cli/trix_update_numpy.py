"""Обновление не имеет права уносить с собой распознавание речи.

Рецепт установки на машинах со старым процессором (ниже `x86-64-v2`)
ставит numpy 1.x: колёса numpy 2.x на таком железе не запускаются вовсе.
`hermes update` переставляет зависимости по замку — и возвращает numpy
2.x поверх подобранного. Голос умирает молча.

Поймано на живой машине 2026-09-05: после чистой установки распознавание
работало (проверено настоящим звуком), после `hermes update` тот же
`import numpy` падает с «your machine doesn't support X86_V2». Клиент
узнал бы об этом, только когда бот перестал бы понимать голосовые.

Поэтому обновление зовёт того же сторожа, что и установка инструментов.
На нормальном процессоре это стоит одного импорта и молчит.
"""

from __future__ import annotations

import logging

logger = logging.getLogger(__name__)


def repair_numpy_after_update(python: str | None = None) -> object | None:
    """Вернуть numpy в рабочее состояние после обновления зависимостей.

    Печатает что-то ТОЛЬКО когда было что чинить: на здоровой машине
    отчёт об обновлении не должен обрастать строчками про numpy.

    Никогда не бросает — обновление уже прошло, и провал восстановления
    не имеет права выглядеть как провал обновления.
    """
    try:
        from hermes_cli.trix_numpy_guard import ensure_runnable_numpy

        result = ensure_runnable_numpy(python)
    except Exception:  # noqa: BLE001 — восстановительный шаг
        logger.debug("Сторож numpy не отработал после обновления", exc_info=True)
        return None

    for line in numpy_report_lines(result):
        print(line)
    return result


def numpy_report_lines(result) -> list[str]:
    """Строки отчёта — пусто, когда чинить было нечего.

    Отделено от печати, чтобы проверять текст, не перехватывая вывод.
    """
    if result is None:
        return []
    if not getattr(result, "repaired", False):
        # Ничего не делали: numpy либо не установлен, либо и так работает.
        return []
    if getattr(result, "ok", False):
        return [
            "  ⚠ Обновление вернуло версию numpy, несовместимую с процессором "
            "этой машины — заменено на рабочую.",
            "    Распознавание речи в порядке.",
        ]
    return [
        "  ⚠ numpy не запускается на процессоре этой машины, и вернуть "
        "рабочую версию не удалось.",
        "    Распознавание голосовых сообщений работать НЕ будет; всё "
        "остальное — будет.",
        "    Повторить попытку: hermes doctor --fix",
    ]
