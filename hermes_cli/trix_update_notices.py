"""Что клиент читает про обновление — и чего он про него НЕ читает.

Апстрим вёл `/update` как разговор с оператором у консоли: наблюдатель
шлюза раз в четыре секунды пересылал в чат свежий кусок вывода
`hermes update` в тройных кавычках, а итоговое сообщение доклеивало
последние 3500 символов того же лога. Клиенту это давало ленту вида
«Pre-update snapshot», «Fast-forward not possible, resetting to match
remote», «Resolved 95 packages», «Refreshing 17 active lazy backends» —
подробности, по которым он не принимает НИ ОДНОГО решения (ответить ему
всё равно нечего: единственный вопрос обновления приходит отдельным
сообщением), и в которых поимённо назван апстримный продукт и его пакеты:
`Updating Hermes Agent...`, `hermes-agent==0.20.0`.

Отсюда два правила этого файла:

* **Клиент получает только исход.** Запуск, вопрос (если он будет) и
  вердикт. Ход обновления не транслируется; лог остаётся на машине в
  `.update_output.txt` и уходит в `gateway.log` — там его читает
  поддержка, у которой есть и машина, и права.
* **Вердикт один на оба пути.** Итог клиенту досылают ДВА места:
  наблюдатель (`_watch_update_progress`) и запасной путь после
  перезапуска шлюза (`_send_update_notification`). В апстриме они
  расходились: наблюдатель различал частичный успех (код 2), а запасной
  путь объявлял тот же код отказом. То есть один и тот же исход клиент
  видел то как «применено частично», то как «не выполнено» — в
  зависимости от того, пережил ли шлюз обновление. Здесь вердикт строит
  одна функция.

Почему не в `gateway/run.py`: там 27 тысяч строк, которые мы регулярно
подтягиваем сверху, и каждая наша строка внутри оплачивается конфликтом
при обновлении (тот же довод, что и в `trix_session_notices.py`).
Почему у каждого `t()` есть `default=`: `agent.i18n._load_catalog`
глотает ошибку разбора каталога и кеширует пустой словарь — без
`default=` клиент получил бы в чат путь ключа.
"""

from __future__ import annotations

from agent.i18n import t

# Код 2 — частичный успех: сам агент обновлён и работоспособен, не
# обновились вспомогательные Node-компоненты (дашборд, терминальный
# интерфейс), которых у клиента в Telegram и так нет. Ни галочка, ни
# отказ тут не годятся: первая скрыла бы правду, второй объявил бы
# сломанным исправный продукт.
PARTIAL_EXIT_CODE = 2


def update_verdict_message(exit_code: int) -> str:
    """Итог обновления одной строкой — без лога и без имени апстрима."""
    if exit_code == 0:
        return t(
            "trix.update.finished",
            # де-брендировано: апстрим говорил "Hermes update finished"
            default="✅ Update finished.",
        )
    if exit_code == PARTIAL_EXIT_CODE:
        return t(
            "trix.update.partial",
            default=(
                "⚠️ Обновление применено частично: сам агент обновлён и "
                "работает, но часть вспомогательных компонентов обновить "
                "не удалось. Ничего делать не нужно — они подтянутся при "
                "следующем обновлении."
            ),
        )
    # Код выхода остаётся в тексте намеренно: клиент пересылает это
    # сообщение в поддержку, и это единственная зацепка, которая у него
    # есть. Всё остальное — путь к логам, `hermes update` в терминале —
    # ему недоступно: он общается с агентом только через мессенджер.
    return t(
        "trix.update.failed_verdict",
        # де-брендировано: апстрим говорил "Hermes update failed"
        default=(
            "❌ Update failed (exit code {exit_code}). "
            "Ask whoever administers this machine to check it."
        ),
        exit_code=exit_code,
    )
