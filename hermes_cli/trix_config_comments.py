"""Переносит на уже установленные машины правки КОММЕНТАРИЕВ в config.yaml.

**Зачем отдельный модуль.** ``trix_config_sync`` переносит клиенту только
отсутствующие КЛЮЧИ и по жёсткому инварианту не меняет ни одной существующей
строки. Для значений это правильно: ответ клиента мы не перетираем. Но
комментарии в этом файле — не украшение, а документация продукта, по которой
клиент понимает, как ведёт себя его машина. Когда документация меняется, а
доехать до машины не может, получается хуже, чем устаревший текст: файл
начинает противоречить себе.

Ровно это и случилось при переходе на полный конфиг (сентябрь 2026). Шапка
старого шаблона говорила «здесь только то, что отличается от значений по
умолчанию», а досев дописывал в тот же файл все 85 секций — то есть шапка
становилась прямой ложью, причём на каждой уже работающей машине. Туда же
попали: имя чужого продукта в объяснении про заклинивший инструмент,
ссылки на внутренние пути репозитория, которых у клиента нет, и объяснение
про ``approvals.timeout``, потерявшее смысл, когда в файле появились все
значения подряд.

**Почему замена ДОСЛОВНАЯ, а не по шаблону.** Каждая правка — пара «ровно
этот старый текст» → «ровно этот новый». Не нашлось дословно — не меняем
ничего: значит клиент правил этот комментарий сам (или сидит на более старой
версии шаблона), и угадывать тут нечего. Это делает модуль безопасным при
повторном запуске: после первой же миграции старого текста в файле нет, и
все последующие прогоны — пустые.

**Чего этот модуль не делает.** Не трогает ни одного значения: в таблице
ниже нет и не может быть строк с данными, это проверяется тестом. Не
двигает блоки по файлу. И не ходит через ``_persist_migration`` —
единственная запись идёт текстом, потому что штатный путь записи миграции
сжимает конфиг по ``strip_defaults`` и выкусил бы из него пустые секции
(поведение апстрима, существующее и до нас).
"""

