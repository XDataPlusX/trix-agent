def _dominant_newline(text: str) -> str:
    """Преобладающий разделитель строк — ``\\r\\n`` или ``\\n``."""
    crlf = text.count("\r\n")
    lf = text.count("\n") - crlf
    return "\r\n" if crlf > lf else "\n"


def sync_client_comments(config_path: Path) -> Tuple[List[str], List[str]]:
    """Применить правки комментариев к ``config_path``.

    Возвращает ``(applied, unmatched)``: метки применённых правок и метки
    тех, чей старый текст в файле не нашёлся дословно.

    ``unmatched`` существует не для красоты. Клиент, поправивший в шапке одну
    строку, по устройству модуля не получает НИ ОДНОЙ правки — и остаётся с
    шапкой, обещающей «здесь только то, что отличается от значений по
    умолчанию», над файлом, в котором теперь все секции. Пока список не
    возвращался, это состояние было ничем не наблюдаемо: обновление молчало,
    и проверка паритета его не видит. Теперь вызывающий может его показать.

    На уже обновлённой машине ``unmatched`` тоже полон — там старого текста
    нет по другой причине, поэтому вызывающий логирует его, а не показывает
    как беду.

    Ошибки глотаются: модуль вызывается из ``hermes update``, и падение здесь
    не имеет права ронять обновление.
    """
    config_path = Path(config_path)
    # Файл, снятый клиентом в режим «только чтение», не переписываем — то же
    # правило и по той же причине, что в ``trix_config_sync``: уважаем защиту,
    # поставленную руками. ``atomic_write_text`` пишет через каталог, поэтому
    # сам по себе на права файла не смотрит и молча переписал бы 444.
    if config_path.exists() and not os.access(config_path, os.W_OK):
        return [], []
    try:
        # newline="" — читаем байты переводов строк как есть, чтобы файл,
        # отредактированный блокнотом (CRLF), не получил ни одного
        # постороннего "\n".
        with open(config_path, encoding="utf-8", newline="") as handle:
            text = handle.read()
    except Exception:
        return [], []

    separator = _dominant_newline(text)
    applied: List[str] = []
    unmatched: List[str] = []
    for label, old, new in COMMENT_REWRITES:
        if separator != "\n":
            old = old.replace("\n", separator)
            new = new.replace("\n", separator)
        if old and old in text:
            text = text.replace(old, new, 1)
            applied.append(label)
        else:
            unmatched.append(label)

    if not applied:
        return [], unmatched

    try:
        atomic_write_text(config_path, text, newline="", preserve_mode=True)
    except Exception:
        return [], unmatched
    return applied, unmatched
