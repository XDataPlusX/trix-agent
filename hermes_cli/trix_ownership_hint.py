"""Готовая команда починки, когда каталог установки принадлежит не тому.

Предупреждение без выхода — тупик. Раньше отказ чистки `__pycache__` по
правам печатал клиенту «Починка: вернуть каталогу установки владельца»:
формально верно, практически бесполезно — человек, который завёл машину
из панели, не обязан знать, чем именно возвращают владельца.

Причина такого дерева одна и известна: шаги установки, работавшие от
root, оставляли за собой файлы внутри каталога, который принадлежит
клиенту. В рецепте это закрыто (владельца отдают после последнего
действия от root), но машины, установленные раньше, останутся такими
навсегда — сами себя они не починят.

Команду продукт **не выполняет**: `sudo` в код мы не добавляем (решение
владельца). Здесь только текст, который можно скопировать.
"""

from __future__ import annotations

import shlex
from pathlib import Path


def ownership_repair_command(root: Path | str, owner: str) -> str:
    """Строка команды, возвращающей *root* во владение *owner*.

    Пути и имя пользователя экранируются: каталог установки может стоять
    где угодно, в том числе по пути с пробелом.
    """
    safe_owner = shlex.quote(owner)
    safe_root = shlex.quote(str(root))
    return f"sudo chown -R {safe_owner}:{safe_owner} {safe_root}"


def ownership_repair_lines(root: Path | str, owner: str) -> list[str]:
    """Готовый блок вывода: что случилось и что набрать, чтобы починить."""
    return [
        "    Продукт продолжит работать, но после обновления возможен "
        "устаревший байт-код.",
        "    Починка — одна команда (спросит пароль этой машины):",
        f"      {ownership_repair_command(root, owner)}",
    ]
