"""Значения клиентского шаблона, которые мастер настройки не вправе перетереть.

**Зачем.** Клиентский `config.yaml` — это `assets/config/trix-config.yaml`:
не голый набор ключей, а документ с русскими комментариями, по которым
клиент читает, как ведёт себя его машина. Мастер (`hermes setup`) при этом
на первой установке безусловно раскладывает свои «рекомендованные значения»
поверх уже лежащего файла — и делает это, не трогая комментарии. Итог хуже,
чем просто сброшенная настройка: восемь строк объяснения продолжают
описывать `idle`, а под ними стоит `none`. Конфиг начинает противоречить
собственной документации, и заметить это можно только сравнив поведение
машины с текстом комментария.

Достижимо это на любой обычной установке: `scripts/install.sh` зовёт
`hermes setup`, а его `is_existing` ложно, пока ключа провайдера нет в
`.env` — то есть всегда, когда оператор вводит ключ внутри самого мастера.

**Правило.** Если у клиента в `config.yaml` уже есть ответ на вопрос,
мастер молчащим умолчанием этот ответ не меняет. Явный вопрос клиенту
(`hermes setup agent`, `hermes config set`) — меняет: там человек отвечает
сам, и перекрывать его ответ никто не собирается.

`session_reset` из этого списка не мог бы досеяться обратно: работать после
мастера нечем — `trix_config_sync` досеивает только ОТСУТСТВУЮЩИЕ ключи, а
`session_reset.mode` после мастера присутствует, просто со сброшенным
значением.
"""

from __future__ import annotations

from typing import Any

# Пути, за которыми закреплено правило выше. Список, а не одна проверка:
# ревью нашло два места в мастере, которые перетирают одно и то же значение,
# и следующее такое место должно попасть под то же правило одной строкой.
CLIENT_PINNED_PATHS: tuple[tuple[str, ...], ...] = (
    ("session_reset", "mode"),
    ("session_reset", "idle_minutes"),
)


def _reachable(config: Any, path: tuple[str, ...]) -> bool:
    """Есть ли по пути осмысленный ответ клиента.

    Пустая строка и None — не ответ: так выглядит ключ, оставленный
    незаполненным, а не выбор.
    """
    node: Any = config
    for part in path:
        if not isinstance(node, dict) or part not in node:
            return False
        node = node[part]
    return node is not None and node != ""


def is_client_pinned(config: Any, *path: str) -> bool:
    """True, если этот путь закреплён списком И у клиента по нему есть ответ."""
    return tuple(path) in CLIENT_PINNED_PATHS and _reachable(config, tuple(path))


def set_unless_client_pinned(config: dict, section: str, key: str, value: Any) -> bool:
    """Записать умолчание мастера, не тронув ответ клиента.

    Возвращает True, если значение записано, и False, если оставлен ответ
    клиента. Возврат нужен вызывающему, чтобы не печатать «применено», когда
    не применено.
    """
    if is_client_pinned(config, section, key):
        return False
    config.setdefault(section, {})[key] = value
    return True
