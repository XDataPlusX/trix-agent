"""Отказ поиска обязан говорить, что с ним делать.

Когда поиск не сработал, клиент видел техническую строку от провайдера —
и оставался с ней наедине. Между тем действие у него ровно одно и оно
простое: сменить поисковик в мастере настройки.

Отдельная причина написать это явно: выбранный по умолчанию DuckDuckGo —
единственный из предлагаемых, который **скрейпит** выдачу, а не ходит в
официальное API. Снято на клиентской машине 2026-09-05: поднятый там же
SearXNG получил от duckduckgo `CAPTCHA`, от brave — «Suspended: too many
requests», от startpage — `Suspended: CAPTCHA`. То есть отказ поиска —
не редкость, а ожидаемое событие, и он почти всегда временный.

Текст попадает в ответ инструмента, который читает модель и пересказывает
клиенту, поэтому он написан как сведения, а не как команда модели. Путей
в конфиге и имён переменных здесь нет — клиенту они ничего не говорят.
"""

from __future__ import annotations

from typing import Any

# Раздел мастера, где меняется поисковик (tools_view.TITLES_RU).
_WIZARD_SECTION = "«Поиск в интернете»"

_ADVICE_MARKER = "мастере настройки"

_ADVICE_GENERAL = (
    "Отказ поиска обычно временный. Если он повторяется, поисковик можно "
    f"сменить в мастере настройки, раздел {_WIZARD_SECTION} — там же "
    "выбирается запасной."
)

_ADVICE_SCRAPER = (
    "DuckDuckGo работает без ключа, но получает выдачу разбором страниц, "
    "а не через официальное API, и потому чаще других упирается в защиту "
    "от роботов. Отказ обычно временный. Если он повторяется, поисковик "
    f"можно сменить в мастере настройки, раздел {_WIZARD_SECTION} — там же "
    "выбирается запасной."
)

# Движки, добывающие выдачу разбором страниц: у них отказ ожидаем.
_SCRAPING_BACKENDS = frozenset({"ddgs", "brave-free"})


def advice_for(backend: str = "") -> str:
    """Совет, соответствующий тому, какой поисковик отказал."""
    name = (backend or "").strip().lower()
    return _ADVICE_SCRAPER if name in _SCRAPING_BACKENDS else _ADVICE_GENERAL


def advise_on_search_failure(response: Any, backend: str = "") -> Any:
    """Дописать совет к неудачному ответу поиска.

    Успешный ответ, не-словарь и ответ без текста ошибки возвращаются как
    есть: советовать не о чем. Повторный вызов ничего не удваивает —
    функция стоит в одной общей точке для обеих веток поиска (цепочка и
    одиночный движок), и лишняя страховка тут дешевле разбирательства.
    """
    if not isinstance(response, dict):
        return response
    if response.get("success"):
        return response

    error = response.get("error")
    if not isinstance(error, str) or not error.strip():
        return response
    if _ADVICE_MARKER in error:
        return response

    return {**response, "error": f"{error.rstrip()} {advice_for(backend)}"}
