#!/usr/bin/env bash
# Калитка релиза: зеркало обязано отдавать ровно то, что ждёт рецепт.
#
# Зачем. Артефакты установки (браузеры, кэши pip/npm, образ песочницы)
# лежат на зеркале, а их контрольные суммы прибиты в рецепте
# `docs/product/cloud_init/hermes_install_v2.sh`. Разойтись они могут
# молча: поднимут версию playwright, пересоберут архив, забудут зеркало --
# и установка у клиента тихо уйдёт на GitHub. Не упадёт, а просто станет
# снова непредсказуемой по времени, и через месяц никто не свяжет
# причину со следствием.
#
# Поэтому проверка стоит В РЕЛИЗЕ, а не в чьей-то памяти: суммы и адреса
# читаются из рецепта, у зеркала спрашивается его собственный `.sha256`,
# и расхождение останавливает выпуск.
#
# Что эта калитка НЕ делает: не качает гигабайт на каждый релиз. Полную
# сверку содержимого делает сама установка -- она считает sha256
# скачанного файла и отбрасывает источник, отдавший не то. Здесь ловится
# другое: зеркало отстало, файл пропал, адрес сменился.
#
#   scripts/trix_mirror_gate.sh          # проверить
#   scripts/trix_mirror_gate.sh --quiet  # только код возврата
set -uo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RECIPE="$REPO_ROOT/docs/product/cloud_init/hermes_install_v2.sh"
QUIET=false
[ "${1:-}" = "--quiet" ] && QUIET=true

say()  { $QUIET || printf '  %s\n' "$*"; }
fail() { printf '\033[0;31m✗ %s\033[0m\n' "$*" >&2; }
ok()   { $QUIET || printf '\033[0;32m✓ %s\033[0m\n' "$*"; }

[ -f "$RECIPE" ] || { fail "рецепт не найден: $RECIPE"; exit 2; }

# Значение по умолчанию из строки вида VAR="${VAR-значение}".
# Берём именно умолчание: оно и уедет в шаблон VMmanager.
recipe_default() {
    sed -n "s/^$1=\"\\\${$1-\\(.*\\)}\"\$/\\1/p" "$RECIPE" | head -1
}

problems=0
# Повтор ВОКРУГ curl, а не внутри него.
#
# `--retry` у curl повторяет не всё: обрыв уже установленного соединения
# он транзиентным не считает, а `--max-time` — общий бюджет на ВСЕ попытки
# сразу, так что тридцати секунд на три захода не хватает, если каждый
# коннект висит по десять. Дважды (релизы 0.1.31, 0.1.32) это лечили
# добавлением `--retry` — и оно не помогло: 2026-09-10 гейт отказал два
# раза подряд на РАЗНЫХ артефактах, при том что те же файлы отдавались с
# другой машины кодом 200 и размером в сотни мегабайт.
#
# Здесь у каждой попытки свой полный бюджет, и пустой ответ считается
# поводом повторить — именно так выглядит обрыв.
fetch_retry() {
    _u="$1"; _mode="$2"; _out=""
    for _try in 1 2 3 4; do
        if [ "$_mode" = "sha" ]; then
            _out="$(curl -fsSL --connect-timeout 15 --max-time 45 "$_u" 2>/dev/null)"
        else
            # Один байт диапазоном: файл может быть в гигабайт, а проверяем
            # лишь то, что он вообще отдаётся.
            _out="$(curl -fsSL --connect-timeout 15 --max-time 45 -r 0-0 \
                    -o /dev/null -w '%{size_download}' "$_u" 2>/dev/null)"
            [ "${_out:-0}" = "0" ] && _out=""
        fi
        [ -n "$_out" ] && { printf '%s' "$_out"; return 0; }
        [ "$_try" -lt 4 ] && sleep 4
    done
    return 1
}

check_one() {
    local label="$1" url_var="$2" sum_var="$3"
    local url sum sidecar got size
    url="$(recipe_default "$url_var")"
    sum="$(recipe_default "$sum_var")"

    if [ -z "$url" ]; then
        say "$label: источник в рецепте пуст -- пропускаю (артефакт выключен)"
        return 0
    fi
    if [ -z "$sum" ]; then
        fail "$label: адрес в рецепте есть, а контрольной суммы нет"
        fail "   без суммы зеркало может подсунуть что угодно, и это не заметят"
        problems=$((problems + 1)); return 1
    fi

    # У каждого артефакта на зеркале лежит свой `.sha256` -- он крошечный,
    # и спросить его дешевле, чем качать гигабайт ради проверки.
    #
    # `--retry` здесь не про медленное зеркало, а про ПЕРВОЕ исходящее
    # соединение: дважды (релизы 0.1.31 и 0.1.32) гейт отказал сразу по всем
    # трём артефактам, а через минуту тот же файл отдавался за 0.2 с и гейт,
    # запущенный руками в том же дереве, проходил. Без повтора одна холодная
    # попытка останавливает релиз, и формулировка отказа при этом утверждает
    # неправду -- «артефакт не выложен», -- то есть посылает разбираться не
    # туда.
    sidecar="$(fetch_retry "$url.sha256" sha | awk '{print $1}' | head -1)"
    if [ -z "$sidecar" ]; then
        fail "$label: зеркало не ответило на $url.sha256 (3 попытки)"
        fail "   проверьте: curl -sI $url.sha256"
        fail "   если отвечает -- повторите релиз; если нет -- артефакт не"
        fail "   выложен или адрес в рецепте сменился"
        problems=$((problems + 1)); return 1
    fi
    if [ "$sidecar" != "$sum" ]; then
        fail "$label: зеркало разошлось с рецептом"
        fail "   рецепт ждёт:   $sum"
        fail "   зеркало отдаёт: $sidecar"
        fail "   пересоберите артефакт и обновите обе стороны"
        problems=$((problems + 1)); return 1
    fi

    # Сам файл обязан быть на месте и непустым: sidecar мог остаться от
    # прошлой выкладки, а артефакт -- не долиться.
    size="$(fetch_retry "$url" head)"
    if [ "${size:-0}" = "0" ]; then
        fail "$label: сумма совпала, но файл не удалось получить за 4 попытки ($url)"
        fail "   это либо зеркало, либо канал ОТСЮДА — отличить можно только проверкой:"
        fail "   curl -sI $url"
        fail "   отвечает 200 — повторите релиз; не отвечает — артефакт не долит"
        problems=$((problems + 1)); return 1
    fi

    say "$label: зеркало совпадает с рецептом"
    return 0
}

$QUIET || printf '\033[0;36m→ Проверяю зеркало против рецепта...\033[0m\n'
check_one "браузеры       " BROWSERS_MIRROR_URL   BROWSERS_ARCHIVE_SHA256
check_one "кэши pip и npm " DEPS_CACHE_SOURCES    DEPS_CACHE_SHA256
check_one "образ песочницы" SANDBOX_IMAGE_SOURCES SANDBOX_IMAGE_SHA256

if [ "$problems" -gt 0 ]; then
    fail "зеркало не готово к релизу: расхождений $problems"
    fail "клиент получит установку, которая молча уйдёт на GitHub и снова"
    fail "станет непредсказуемой по времени"
    exit 1
fi
ok "зеркало готово: всё, что ждёт рецепт, на месте"
